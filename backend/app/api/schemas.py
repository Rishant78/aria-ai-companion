from enum import Enum
from typing import Optional
from pydantic import BaseModel, Field, ConfigDict, model_validator


class EmotionEnum(str, Enum):
    neutral = "neutral"
    happy = "happy"
    sad = "sad"
    angry = "angry"
    relaxed = "relaxed"
    surprised = "surprised"
    curious = "curious"
    shy = "shy"
    confused = "confused"


class GestureEnum(str, Enum):
    wave = "wave"
    greeting = "greeting"
    explain = "explain"
    think = "think"
    shrug = "shrug"
    laugh = "laugh"
    shy = "shy"
    reassure = "reassure"


class SpeechIntentEnum(str, Enum):
    conversational = "conversational"
    excited = "excited"
    playful = "playful"
    gentle = "gentle"
    reassuring = "reassuring"
    curious = "curious"
    serious = "serious"
    surprised = "surprised"


class MouthAnimationProfileEnum(str, Enum):
    soft_conversation = "soft_conversation"
    energetic = "energetic"
    gentle = "gentle"
    deliberate = "deliberate"
    minimal = "minimal"


class CompanionResponse(BaseModel):
    """Structured response payload generated by Google Gemini and validated via Pydantic."""
    model_config = ConfigDict(extra="forbid")

    response_text: str = Field(..., min_length=1, description="Companion dialogue response text")
    emotion: EmotionEnum = Field(..., description="Facial emotional expression")
    emotion_intensity: float = Field(..., ge=0.0, le=1.0, description="Emotion intensity clamped between 0.0 and 1.0")
    gesture: Optional[GestureEnum] = Field(None, description="Upper-body gesture or null")
    gesture_intensity: float = Field(..., ge=0.0, le=1.0, description="Gesture intensity between 0.0 and 1.0")
    speech_intent: SpeechIntentEnum = Field(..., description="Speech intent style")
    mouth_animation_profile: MouthAnimationProfileEnum = Field(..., description="Procedural mouth viseme cadence profile")

    @model_validator(mode="after")
    def validate_gesture_intensity(self) -> "CompanionResponse":
        if self.gesture is None:
            self.gesture_intensity = 0.0
        return self


class ChatRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")

    session_id: str = Field(..., description="UUID session identifier")
    message: str = Field(..., min_length=1, max_length=2000, description="User message content")
    voice_enabled: Optional[bool] = Field(
        default=True,
        description="Whether to generate companion TTS voice synthesis (default True)",
    )


class ChatResponse(BaseModel):
    model_config = ConfigDict(extra="forbid")

    session_id: str = Field(..., description="UUID session identifier")
    response_text: str = Field(..., description="Companion dialogue text")
    emotion: EmotionEnum = Field(..., description="Validated emotion")
    emotion_intensity: float = Field(..., description="Intensity 0.0 to 1.0")
    gesture: Optional[GestureEnum] = Field(None, description="Upper body gesture or null")
    gesture_intensity: float = Field(..., description="Gesture intensity (0.0 if gesture is null)")
    speech_intent: SpeechIntentEnum = Field(..., description="Speech intent category")
    mouth_animation_profile: MouthAnimationProfileEnum = Field(..., description="Mouth cadence profile")
    created_at: str = Field(..., description="ISO-8601 generation timestamp")

    # Milestone 7: Voice Synthesis Metadata
    audio_data: Optional[str] = Field(None, description="Base64-encoded audio payload or null if unavailable")
    audio_mime_type: Optional[str] = Field(None, description="Audio container MIME type (e.g. audio/wav)")
    audio_duration: Optional[float] = Field(None, gt=0, description="Audio duration in seconds")
    audio_sample_rate: Optional[int] = Field(None, gt=0, description="Audio sample rate in Hz")


class CreateSessionResponse(BaseModel):
    model_config = ConfigDict(extra="forbid")

    session_id: str = Field(..., description="Newly generated UUID session identifier")
    created_at: str = Field(..., description="ISO-8601 creation timestamp")


class DeleteSessionResponse(BaseModel):
    model_config = ConfigDict(extra="forbid")

    session_id: str = Field(..., description="Target session identifier")
    deleted: bool = Field(..., description="Whether the session was successfully deleted")


class HealthResponse(BaseModel):
    model_config = ConfigDict(extra="forbid")

    status: str = Field(..., description="Service status")
    model: str = Field(..., description="Configured Gemini model identifier")
    timestamp: str = Field(..., description="ISO-8601 current server timestamp")

